import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "src"))

import matplotlib  # noqa: E402

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

from atml4.common.plotting import apply_style  # noqa: E402

OUT = ROOT / "report/figs"
LABEL, SMALL = 7, 6.5
OI = {"blue": "#0072B2", "orange": "#E69F00", "green": "#009E73", "verm": "#D55E00", "purple": "#CC79A7",
      "sky": "#56B4E9", "yellow": "#F0E442", "black": "#000000", "grey": "#7F7F7F"}


def setup():
    apply_style()
    plt.rcParams.update({"axes.labelsize": LABEL, "font.size": LABEL, "xtick.labelsize": SMALL,
                         "ytick.labelsize": SMALL, "legend.fontsize": SMALL, "savefig.bbox": None,
                         "figure.constrained_layout.use": True, "legend.handlelength": 1.4,
                         "legend.borderaxespad": 0.2, "legend.labelspacing": 0.25, "legend.handletextpad": 0.4,
                         "axes.labelpad": 1.5, "xtick.major.pad": 1.5, "ytick.major.pad": 1.5,
                         "xtick.major.size": 2.5, "ytick.major.size": 2.5, "xtick.minor.size": 1.5,
                         "ytick.minor.size": 1.5})


def fig(w, h, **kw):
    f = plt.figure(figsize=(w, h), **kw)
    f.get_layout_engine().set(w_pad=0.02, h_pad=0.02, wspace=0.03, hspace=0.03)
    return f


def panel(ax, letter, dx=-0.02, dy=1.01):
    ax.text(dx, dy, f"({letter})", transform=ax.transAxes, fontsize=SMALL, fontweight="bold", ha="right",
            va="bottom")


def save(f, task: int, name: str, w: float, h: float) -> Path:
    d = OUT / f"task{task}"
    d.mkdir(parents=True, exist_ok=True)
    p = d / name
    assert abs(f.get_figwidth() - w) < 1e-6 and abs(f.get_figheight() - h) < 1e-6
    f.savefig(p, format="pdf", bbox_inches=None)
    plt.close(f)
    return p


def load(path):
    from atml4.common.io import load_jsonl_result, load_result

    p = ROOT / path
    if ".jsonl" in p.name:
        return load_jsonl_result(p)[1]
    return load_result(p)[1]


# ---------------------------------------------------------------- tables
def neg(x: str) -> str:
    return x.replace("-", "$-$") if x.startswith("-") or " -" in x or "[-" in x else x


def num(v, fmt="{:.2f}", signed=False):
    if v is None:
        return ""
    s = (("{:+" + fmt[2:]) if signed else fmt).format(v)
    return s.replace("-", "$-$")


def ci(c, scale=1.0, fmt="{:.2f}", signed=True):
    if not c:
        return ""
    return f"{num(c['point'] * scale, fmt, signed)} [{num(c['ci_low'] * scale, fmt)}, {num(c['ci_high'] * scale, fmt)}]"


def write_tab(task: int, name: str, colspec: str, header: list[str], rows: list, notes: str = "") -> Path:
    """booktabs tabular-only fragment. rows: list of lists, or the string 'MID' for a midrule."""
    d = OUT / f"task{task}"
    d.mkdir(parents=True, exist_ok=True)
    lines = [f"% generated by scripts/report (do not edit by hand)", f"\\begin{{tabular}}{{{colspec}}}", "\\toprule",
             " & ".join(header) + " \\\\", "\\midrule"]
    for r in rows:
        lines.append("\\midrule" if r == "MID" else " & ".join(str(x) for x in r) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}"]
    if notes:
        lines.append(notes)
    p = d / name
    p.write_text("\n".join(lines) + "\n")
    return p


MANIFEST: list[tuple[str, str, list[str]]] = []


def record(out: Path, script: str, sources: list[str]):
    MANIFEST.append((str(out.relative_to(ROOT)), script, sources))


def dump_manifest(script: str):
    d = OUT / f".manifest_{Path(script).stem}.json"
    d.write_text(json.dumps(MANIFEST, indent=1))
